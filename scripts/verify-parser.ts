interface Assertion {
  label: string;
  actual: unknown;
  expected: unknown;
  pass: boolean;
}

function check<T>(label: string, actual: T, expected: T): Assertion {
  return { label, actual, expected, pass: actual === expected };
}

function main(): void {
  const parsed = parseHurdat2(SYNTHETIC_KATRINA);
  if (parsed.length !== 1) {
    console.error(`[verify-parser] expected 1 storm, got ${parsed.length}`);
    process.exit(1);
  }
  const p = parsed[0];
  if (!p) { process.exit(1); }
  const { summary } = computeStormSummary(p);
  const assertions: Assertion[] = [
    check("id", summary.id, "AL122005"),
    check("name", summary.name, "KATRINA"),
    check("year", summary.year, 2005),
    check("peakCat", summary.peakCat, "c5"),
    check("peakKt", summary.peakKt, 150),
    check("minMb", summary.minMb, 902),
    check("landfalls", summary.landfalls, 2)
  ];
  let failed = 0;
  for (const a of assertions) {
    const status = a.pass ? "OK " : "FAIL";
    console.log(`[verify-parser] ${status}  ${a.label}: actual=${String(a.actual)} expected=${String(a.expected)}`);
    if (!a.pass) failed += 1;
  }
  if (failed > 0) {
    console.error(`[verify-parser] ${failed} assertion(s) failed`);
    process.exit(1);
  }
  console.log(`[verify-parser] all ${assertions.length} Katrina assertions pass`);
}

main();
